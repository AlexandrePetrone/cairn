<?php

declare(strict_types=1);

namespace App\Entity;

use App\Entity\Enum\ApiTokenScope;
use App\Repository\ApiTokenRepository;
use Doctrine\ORM\Mapping as ORM;

use function Symfony\Component\Clock\now;

/**
 * A personal token an internal user gives to a program calling the API in
 * their name: the program sees and does what the user may, narrowed by the
 * scope. Only the SHA-256 of the secret is kept, so the secret is shown
 * once, when the token is created. A token is revoked, never deleted.
 */
#[ORM\Entity(repositoryClass: ApiTokenRepository::class)]
#[ORM\UniqueConstraint(name: 'uniq_api_token_hash', columns: ['hash'])]
class ApiToken
{
    public const string PREFIX = 'cairn_';
    public const string PATTERN = '/^cairn_[0-9a-f]{64}$/';

    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column]
    private ?int $id = null;

    #[ORM\ManyToOne]
    #[ORM\JoinColumn(nullable: false)]
    private User $user;

    #[ORM\Column(length: 80)]
    private string $name;

    #[ORM\Column(length: 64)]
    private string $hash;

    #[ORM\Column(enumType: ApiTokenScope::class)]
    private ApiTokenScope $scope;

    #[ORM\Column]
    private \DateTimeImmutable $createdAt;

    #[ORM\Column(nullable: true)]
    private ?\DateTimeImmutable $expiresAt;

    #[ORM\Column(nullable: true)]
    private ?\DateTimeImmutable $lastUsedAt = null;

    #[ORM\Column(nullable: true)]
    private ?\DateTimeImmutable $revokedAt = null;

    /**
     * @param string $secret the secret generated by newSecret(), which the caller hands to the user
     */
    public function __construct(User $user, string $name, string $secret, ApiTokenScope $scope, ?\DateTimeImmutable $expiresAt = null)
    {
        $this->user = $user;
        $this->name = trim($name);
        $this->hash = self::hash($secret);
        $this->scope = $scope;
        $this->createdAt = now();
        $this->expiresAt = $expiresAt;
    }

    public static function newSecret(): string
    {
        return self::PREFIX.bin2hex(random_bytes(32));
    }

    /**
     * The secrets are long random strings: a plain SHA-256 is enough, and
     * lets the token be found by its hash.
     */
    public static function hash(string $secret): string
    {
        return hash('sha256', $secret);
    }

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getUser(): User
    {
        return $this->user;
    }

    public function getName(): string
    {
        return $this->name;
    }

    public function getScope(): ApiTokenScope
    {
        return $this->scope;
    }

    public function getCreatedAt(): \DateTimeImmutable
    {
        return $this->createdAt;
    }

    public function getExpiresAt(): ?\DateTimeImmutable
    {
        return $this->expiresAt;
    }

    public function getLastUsedAt(): ?\DateTimeImmutable
    {
        return $this->lastUsedAt;
    }

    public function getRevokedAt(): ?\DateTimeImmutable
    {
        return $this->revokedAt;
    }

    public function isRevoked(): bool
    {
        return null !== $this->revokedAt;
    }

    public function isExpired(\DateTimeImmutable $now): bool
    {
        return null !== $this->expiresAt && $this->expiresAt <= $now;
    }

    /**
     * Whether the token still opens the API: neither revoked nor expired.
     * Whether its user still may is the caller's to check.
     */
    public function isUsable(\DateTimeImmutable $now): bool
    {
        return !$this->isRevoked() && !$this->isExpired($now);
    }

    public function revoke(): void
    {
        $this->revokedAt ??= now();
    }
}
